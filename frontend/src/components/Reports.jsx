function Reports({ history }) {


    const generateReport = (scan) => {

        const findings = scan.findings || [];


        const findingsHTML = findings.length > 0

            ? findings.map((finding, index) => {

                return `
                    <div class="finding">

                        <h3>
                            Finding ${index + 1}
                        </h3>

                        <p>
                            <strong>Service:</strong>
                            ${finding.service || "N/A"}
                        </p>

                        <p>
                            <strong>Port:</strong>
                            ${finding.port || "N/A"}
                        </p>

                        <p>
                            <strong>State:</strong>
                            ${finding.state || "N/A"}
                        </p>

                        <p>
                            <strong>Severity:</strong>
                            ${finding.severity || "N/A"}
                        </p>

                        <p>
                            <strong>Description:</strong>
                            ${finding.description || "N/A"}
                        </p>

                    </div>
                `;

            }).join("")

            : `
                <p>
                    No findings were returned by the scanner.
                </p>
            `;


        const reportWindow = window.open(
            "",
            "_blank"
        );


        if (!reportWindow) {

            alert(
                "Please allow pop-ups to generate the report."
            );

            return;
        }


        reportWindow.document.write(`

            <!DOCTYPE html>

            <html>

            <head>

                <title>
                    Unified Security Scanner Report
                </title>

                <style>

                    body {
                        font-family: Arial, sans-serif;
                        padding: 40px;
                        color: #222;
                    }

                    h1 {
                        margin-bottom: 5px;
                    }

                    .subtitle {
                        color: #666;
                        margin-bottom: 30px;
                    }

                    .info {
                        background: #f5f5f5;
                        padding: 20px;
                        margin-bottom: 25px;
                    }

                    .finding {
                        border: 1px solid #ddd;
                        padding: 20px;
                        margin-bottom: 15px;
                        border-radius: 8px;
                    }

                    .finding h3 {
                        margin-top: 0;
                    }

                    .footer {
                        margin-top: 40px;
                        color: #777;
                        font-size: 12px;
                    }

                </style>

            </head>


            <body>

                <h1>
                    Unified Security Scanner
                </h1>

                <div class="subtitle">
                    Security Scan Report
                </div>


                <div class="info">

                    <p>
                        <strong>Scanner:</strong>
                        ${scan.scanner.toUpperCase()}
                    </p>

                    <p>
                        <strong>Target:</strong>
                        ${scan.target}
                    </p>

                    <p>
                        <strong>Status:</strong>
                        ${scan.status}
                    </p>

                    <p>
                        <strong>Date:</strong>
                        ${scan.date}
                    </p>

                    <p>
                        <strong>Total Findings:</strong>
                        ${findings.length}
                    </p>

                </div>


                <h2>
                    Findings
                </h2>

                ${findingsHTML}


                <div class="footer">
                    Generated by Unified Security Scanner
                </div>


                <script>

                    window.onload = function() {

                        window.print();

                    };

                </script>

            </body>

            </html>

        `);


        reportWindow.document.close();

    };


    return (

        <section className="page-section">

            <div className="page-header">

                <div>

                    <h2>Security Reports</h2>

                    <p>
                        Generate reports from completed scans.
                    </p>

                </div>

            </div>


            {history.length === 0 ? (

                <div className="empty-state">

                    <h3>No reports available</h3>

                    <p>
                        Complete a scan first to generate
                        a security report.
                    </p>

                </div>

            ) : (

                <div className="report-list">

                    {history.map((scan) => (

                        <div
                            className="report-card"
                            key={scan.id}
                        >

                            <div>

                                <h3>
                                    {scan.scanner.toUpperCase()} Report
                                </h3>

                                <p>
                                    Target:{" "}
                                    <strong>
                                        {scan.target}
                                    </strong>
                                </p>

                                <p>
                                    {scan.date}
                                </p>

                                <p>
                                    {scan.findings.length} Findings
                                </p>

                            </div>


                            <button
                                className="primary-button"
                                onClick={() =>
                                    generateReport(scan)
                                }
                            >
                                Generate PDF
                            </button>

                        </div>

                    ))}

                </div>

            )}

        </section>
    );
}


export default Reports;